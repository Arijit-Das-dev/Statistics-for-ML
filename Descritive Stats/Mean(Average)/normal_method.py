# Mean using normal method
# Sample mean
# Population mean

# Population mean
population = [12, 13, 22, 24, 34, 15]

xi = sum(population)
N = len(population)

U = xi/N
print("Population mean : ", U)

# Sample mean
sample = [12, 13, 24]

xi = sum(sample)
n = len(sample)

X = xi/n
print("Sample mean : ", X)